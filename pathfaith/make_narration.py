"""Fill the narration script's numbers from the same macros the report uses.

The script is written once, in video/narration_template.md, with tokens such as
{wnKendallTauGradVsDrop|num}. This replaces each token with the value defined
in report/numbers.tex, formatted for reading aloud, and writes
video/narration.md. It refuses to write a script with a missing or placeholder
number in it, so the narration can never quote a figure the data does not back.

Formats:
  {x}        the macro's text as it is
  {x|num}    a decimal rounded to two places, with "minus" spelled out
  {x|pct}    a share in [0, 1] read as a whole percent
  {x|pctv}   a value already in percent, read as a whole percent

It also prints the slide timings parsed from the "(NNs)" in each heading, which
is what build_video.sh uses.

Usage:
    python -m pathfaith.make_narration
"""
from __future__ import annotations

import argparse
import re
import sys

TOKEN = re.compile(r'\{((?:wn|fb|cx|nl|all)[A-Z][A-Za-z]*)(?:\|(num|pct|pctv))?\}')


def macros(path: str) -> dict:
    defined = {}
    for name, val in re.findall(r'\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}\s*$',
                                open(path).read(), flags=re.M):
        defined[name] = val
    return defined


def spoken(value: str, how: str | None) -> str:
    raw = value.replace('{,}', ',').replace(r'\ensuremath{-}', '-')
    if how is None:
        return raw
    x = float(raw.replace(',', ''))
    if how == 'num':
        s = f'{abs(x):.2f}'
        return ('minus ' if x < 0 and s != '0.00' else '') + s
    if how == 'pct':
        return f'{round(100 * x):d} percent'
    if how == 'pctv':
        return f'{round(x):d} percent'
    raise ValueError(how)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--template', default='video/narration_template.md')
    ap.add_argument('--numbers', default='report/numbers.tex')
    ap.add_argument('--out', default='video/narration.md')
    args = ap.parse_args()

    text = open(args.template).read()
    defined = macros(args.numbers)
    missing = sorted({m.group(1) for m in TOKEN.finditer(text) if m.group(1) not in defined})
    if missing:
        print('not written: these numbers are not in the data yet:', ', '.join(missing))
        return 1
    out = TOKEN.sub(lambda m: spoken(defined[m.group(1)], m.group(2)), text)

    # drop the template's own preamble, keep everything from the first slide on
    body = out[out.index('## Slide 1'):]
    head = ('# Narration script\n\n'
            'Generated by `python -m pathfaith.make_narration` from '
            '`video/narration_template.md`; every number below comes from '
            '`report/numbers.tex`. The bracketed time is how long the video holds '
            'that slide. Read at about 150 words a minute.\n\n---\n\n')
    if '\u2014' in out:
        print('not written: the template contains an em dash')
        return 1
    with open(args.out, 'w') as f:
        f.write(head + body)

    secs = [int(s) for s in re.findall(r'^## Slide \d+,.*\((\d+)s\)\s*$', text, flags=re.M)]
    words = []
    for sec in re.split(r'^## ', body, flags=re.M)[1:]:
        title, _, rest = sec.partition('\n')
        words.append((title.strip(), len(re.findall(r"[A-Za-z0-9'.-]+", rest.replace('---', '')))))
    print(f'wrote {args.out}')
    print(f'{"section":55s} words  needs  slot')
    slots = iter(secs)
    for title, n in words:
        need = n / 150 * 60
        slot = next(slots) if title.startswith('Slide') else None
        flag = '' if slot is None or need <= slot + 3 else '  <- too long for its slot'
        print(f'{title[:55]:55s} {n:5d} {need:5.0f}s ' + (f'{slot:4d}s' if slot else '  run') + flag)
    print(f'slides: {sum(secs)}s plus the demo recording')
    return 0


if __name__ == '__main__':
    sys.exit(main())
