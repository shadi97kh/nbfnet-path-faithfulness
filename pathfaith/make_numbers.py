r"""Emit every number the report quotes as a LaTeX macro.

No figure is typed into the manuscript by hand. The report says \wnComp and
this file decides what that is, so the text cannot drift from the data and a
reader can regenerate the whole thing from the results files.

Usage:
    python -m pathfaith.make_numbers --out report/numbers.tex
"""
from __future__ import annotations

import argparse
import json
import math
import os
import re

import numpy as np

from pathfaith.analyze import load, Summary, boot

MACRO = {'WN18RR': 'wn', 'FB15k237': 'fb', 'CoDExSmall': 'cx', 'NELL23k': 'nl'}


def fmt(x: float, nd: int = 3) -> str:
    if x != x:
        return '--'
    out = f'{x:.{nd}f}'
    # a value that rounds to zero should not carry a minus sign
    if out.startswith('-') and out.lstrip('-').strip('0.') == '':
        return out[1:]
    # a real minus sign that cannot be split from its number at a line break
    return r'\ensuremath{-}' + out[1:] if out.startswith('-') else out


def pct(x: float, nd: int = 1) -> str:
    return fmt(100 * x, nd)


DIGITS = str.maketrans({'0': 'Zero', '1': 'One', '2': 'Two', '3': 'Three',
                        '4': 'Four', '5': 'Five', '6': 'Six', '7': 'Seven',
                        '8': 'Eight', '9': 'Nine'})


def macro_name(*parts: str) -> str:
    """A LaTeX-legal control sequence: letters only, so digits are spelled."""
    return ''.join(parts).translate(DIGITS)


def emit(name: str, value: str, out: list) -> None:
    out.append(f'\\newcommand{{\\{macro_name(name)}}}{{{value}}}')


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--results', default='results')
    ap.add_argument('--out', default='report/numbers.tex')
    args = ap.parse_args()

    lines = ['% generated by pathfaith.make_numbers -- do not edit by hand']
    summaries = {}

    for ds, pre in MACRO.items():
        # the baseline run that scored the most test triples wins (the full
        # test set when it exists, otherwise the largest sample)
        import glob
        cands = [(json.load(open(f)).get('n_triples', 0), f) for f in
                 glob.glob(os.path.join(args.results, f'baseline_{ds.lower()}*.json'))]
        base_path = max(cands)[1] if cands else ''
        if os.path.exists(base_path):
            b = json.load(open(base_path))
            emit(f'{pre}Mrr', fmt(b['mrr']), lines)
            emit(f'{pre}HitsOne', fmt(b['hits@1']), lines)
            emit(f'{pre}HitsThree', fmt(b['hits@3']), lines)
            emit(f'{pre}HitsTen', fmt(b['hits@10']), lines)
            emit(f'{pre}BaseN', str(b['n_triples']), lines)

        path = os.path.join(args.results, f'paths_{ds.lower()}_seed0.jsonl')
        if not os.path.exists(path):
            continue
        meta, rows = load(path)
        rep = Summary(dataset=ds, rows=rows).report()
        summaries[ds] = (meta, rows, rep)

        emit(f'{pre}Nodes', f"{meta['num_nodes']:,}".replace(',', '{,}'), lines)
        emit(f'{pre}Edges', f"{meta['num_edges']:,}".replace(',', '{,}'), lines)
        emit(f'{pre}Queries', str(len(rows)), lines)
        emit(f'{pre}Scanned', str(meta['n_scanned']), lines)
        emit(f'{pre}Pool', str(meta['pool']), lines)
        # forward relation types, which is half of what the graph stores
        emit(f'{pre}RelCount', str(meta.get('num_relations', 0) // 2 or '--'), lines)
        emit(f'{pre}Topk', str(meta['topk']), lines)

        def ci(key, nd=3, as_pct=False, macro=None):
            m, lo, hi = rep[key]
            f = (lambda v: pct(v, nd)) if as_pct else (lambda v: fmt(v, nd))
            nm = macro or macro_name(pre, *[w.capitalize() for w in key.split('_')])
            emit(nm, f(m), lines)
            emit(nm + 'CI', f'[{f(lo)}, {f(hi)}]', lines)

        for k in ['comprehensiveness', 'comprehensiveness_random', 'comp_minus_random',
                  'sufficiency', 'base_prob', 'single_edge_drop',
                  'rewire_drop_on_gold', 'rewire_gain_on_target']:
            ci(k, 4)
        for k in ['top1_is_best', 'top1_chance', 'top1_over_chance',
                  'comp_frac_of_base', 'comp_random_frac_of_base',
                  'bottleneck_frac', 'distinct_edge_ratio', 'single_edge_recovers_frac',
                  'suff_frac_of_base', 'kendall_tau_grad_vs_drop', 'top_minus_bottom',
                  'mean_drop_top_quartile', 'mean_drop_bottom_quartile']:
            ci(k, 3)
        for k in ['frac_rank_broken', 'frac_single_edge_breaks', 'frac_rewire_followed',
                  'frac_comp_negative', 'frac_comp_meaningful', 'frac_suff_above_one']:
            ci(k, 1, as_pct=True)
        emit(f'{pre}FracPoolTied', pct(rep['frac_pool_fully_tied'], 1), lines)
        # the rewire edit costs the old answer far more than it buys the new
        # one; that ratio is the number the portability argument turns on
        gold, gain = rep['rewire_drop_on_gold'][0], rep['rewire_gain_on_target'][0]
        emit(f'{pre}RewireAsymmetry', fmt(gold / gain, 1) if gain > 1e-9 else '--', lines)
        emit(f'{pre}RankAfter', fmt(rep['rank_after_deletion'][0], 0), lines)
        emit(f'{pre}Forwards', fmt(rep['forwards_per_query'][0], 1), lines)
        # per-path against per-edge occlusion cost, so the recommendation in
        # the cost section is checkable rather than asserted
        emit(f'{pre}Paths', fmt(np.mean([r['n_paths'] for r in rows]), 1), lines)
        emit(f'{pre}DistinctEdges',
             fmt(np.mean([r['n_distinct_edges'] for r in rows]), 1), lines)
        # median, not mean: the machine was shared with other work at times,
        # and a few slowed queries should not set the quoted cost
        emit(f'{pre}Seconds', fmt(float(np.median([r['seconds'] for r in rows])), 1), lines)

        # The symmetric-relation split. WN18RR keeps relations whose reverse
        # sits in the training graph, which turns some queries into a one-hop
        # lookup; the central results are therefore reported on both halves so
        # a reader can see which findings survive the control.
        flagged = [r for r in rows if 'reverse_in_graph' in r]
        if len(flagged) == len(rows) and rows:
            for tag, sub in (('Rev', [r for r in flagged if r['reverse_in_graph']]),
                             ('NoRev', [r for r in flagged if not r['reverse_in_graph']])):
                if not sub:
                    continue
                sr = Summary(dataset=ds, rows=sub).report()
                emit(f'{pre}{tag}N', str(len(sub)), lines)
                for key, nd, as_pct in [('comp_frac_of_base', 3, False),
                                        ('suff_frac_of_base', 3, False),
                                        ('bottleneck_frac', 3, False),
                                        ('distinct_edge_ratio', 3, False),
                                        ('single_edge_recovers_frac', 3, False),
                                        ('kendall_tau_grad_vs_drop', 3, False),
                                        ('rewire_drop_on_gold', 4, False),
                                        ('rewire_gain_on_target', 4, False),
                                        ('top1_is_best', 3, False),
                                        ('top1_chance', 3, False),
                                        ('frac_single_edge_breaks', 1, True)]:
                    m, lo, hi = sr[key]
                    f = (lambda v: pct(v, nd)) if as_pct else (lambda v: fmt(v, nd))
                    nm = macro_name(pre, tag, *[w.capitalize() for w in key.split('_')])
                    emit(nm, f(m), lines)
                    emit(nm + 'CI', f'[{f(lo)}, {f(hi)}]', lines)
            emit(f'{pre}RevPct', pct(np.mean([r['reverse_in_graph'] for r in flagged]), 1), lines)
            emit(f'{pre}FwdPct', pct(np.mean([r['forward_in_graph'] for r in flagged]), 1), lines)

        # structural controls added by pathfaith.enrich
        if rows and all('tail_degree' in r for r in rows):
            deg = [r['tail_degree'] for r in rows]
            emit(f'{pre}TailDegMedian', str(int(np.median(deg))), lines)
            emit(f'{pre}TailDegMin', str(int(np.min(deg))), lines)
            emit(f'{pre}TailLeafPct',
                 pct(np.mean([r['tail_is_leaf'] for r in rows]), 1), lines)
            hi = [r for r in rows if r['tail_degree'] >= 4]
            if hi:
                m, lo, up = boot([r['bottleneck_drop'] / r['comp_topk']
                                  for r in hi if r['comp_topk'] > 1e-6])
                emit(f'{pre}SingleEdgeRecoversHiDeg', fmt(m, 3), lines)
                emit(f'{pre}SingleEdgeRecoversHiDegCI', f'[{fmt(lo,3)}, {fmt(up,3)}]', lines)
                emit(f'{pre}HiDegN', str(len(hi)), lines)

    # Benchmark reliability: what a five-query study could have reported, the
    # interval at full size, and split-half agreement. See pathfaith.reliability.
    rel_path = os.path.join(args.results, 'reliability.json')
    if os.path.exists(rel_path):
        rel = json.load(open(rel_path))
        tags = {'WN18RR': 'wn', 'FB15k-237': 'fb', 'CoDEx-S': 'cx', 'NELL23k': 'nl'}
        keys = {'top path minus chance': 'TopGap',
                'one edge recovers (share of effect)': 'Recover',
                'delete shortlist (share of p removed)': 'Comp',
                'paths sharing one edge': 'Share'}
        for ds, metrics in rel.items():
            pre = tags.get(ds)
            if not pre:
                continue
            for m, short in keys.items():
                r = metrics.get(m)
                if not r:
                    continue
                emit(f'{pre}Rel{short}N', str(r['n']), lines)
                emit(f'{pre}Rel{short}Half', fmt(r['ci_halfwidth'], 3), lines)
                emit(f'{pre}Rel{short}SplitGap', fmt(r['split_half_p95_gap'], 3), lines)
                if r.get('five_query_block_range'):
                    lo, hi = r['five_query_block_range']
                    emit(f'{pre}Rel{short}FiveLo', fmt(lo, 2), lines)
                    emit(f'{pre}Rel{short}FiveHi', fmt(hi, 2), lines)
                # where the running estimate last pointed the other way, from
                # n = 10 on; written as a phrase so the text stays true either way
                curve = r.get('curve') or []
                if curve:
                    final = curve[-1][1]
                    emit(f'{pre}Rel{short}Estimate', fmt(final, 3), lines)
                    opp = [c[0] for c in curve if c[0] >= 10 and c[1] * final < 0]
                    emit(f'{pre}Rel{short}SignNote',
                         (f'the running estimate still had the opposite sign at {max(opp)} queries'
                          if opp else 'its sign does not change from 10 queries on'), lines)
                if r.get('five_query_ci') and r['five_query_ci'][0] == r['five_query_ci'][0]:
                    emit(f'{pre}Rel{short}FiveHalf',
                         fmt((r['five_query_ci'][1] - r['five_query_ci'][0]) / 2, 3), lines)

    # neuromodulatory channels (pathfaith.neuromod), and the ranking metrics
    # from the retrieval lectures applied to the path benchmark
    from pathfaith.analyze_neuromod import rows_of, summarize as nm_summarize, ranking_metrics
    nm_keys = {'silence_best': ('NmBest', 3, False), 'silence_explained': ('NmExplained', 3, False),
               'silence_random': ('NmRandom', 3, False), 'joint': ('NmJoint', 3, False),
               'joint_half': ('NmJointHalf', 3, False), 'content': ('NmContent', 3, False),
               'context_minus_content': ('NmContextGap', 3, False),
               'half_dose': ('NmHalfDose', 2, False), 'switch_like': ('NmSwitch', 1, True),
               'inverted_u': ('NmInvertedU', 1, True), 'sign_agree': ('NmSignAgree', 1, True),
               'grad_within_2x': ('NmWithinTwo', 1, True), 'tau': ('NmTau', 3, False),
               'top_explained': ('NmTopExplained', 1, True),
               'top_is_query_rel': ('NmTopQueryRel', 1, True)}
    nm_gaps, nm_total = [], 0
    for ds, pre in MACRO.items():
        p = os.path.join(args.results, f'neuromod_{ds.lower()}_seed0.jsonl')
        if os.path.exists(p):
            _, nrows = rows_of(p)
            if nrows:
                ns, _, _ = nm_summarize(nrows)
                emit(f'{pre}NmN', str(len(nrows)), lines)
                for key, (nm, nd, as_pct) in nm_keys.items():
                    m, lo, hi, n = ns[key]
                    if n == 0 or m != m:
                        continue
                    f = (lambda v, nd=nd: pct(v, nd)) if as_pct else (lambda v, nd=nd: fmt(v, nd))
                    emit(pre + nm, f(m), lines)
                    emit(pre + nm + 'CI', f'[{f(lo)}, {f(hi)}]', lines)
                gap = ns['val_gap_max'][0]
                nm_gaps.append(gap)
                nm_total += len(nrows)
                emit(f'{pre}NmCheckGap', '0' if gap == 0 else
                     r'\ensuremath{%s\times 10^{%d}}' % (f'{gap / 10 ** math.floor(math.log10(gap)):.0f}',
                                                     math.floor(math.log10(gap))), lines)
        pth = os.path.join(args.results, f'paths_{ds.lower()}_seed0.jsonl')
        if os.path.exists(pth):
            _, prow = load(pth)
            rm = ranking_metrics(prow)
            for key, nm in (('ndcg5', 'NdcgFive'), ('ndcg5_chance', 'NdcgFiveChance'),
                            ('mrr_best', 'MrrBest'), ('mrr_best_chance', 'MrrBestChance')):
                m, lo, hi, n = rm[key]
                if n:
                    emit(pre + nm, fmt(m, 3), lines)
                    emit(pre + nm + 'CI', f'[{fmt(lo, 3)}, {fmt(hi, 3)}]', lines)

    def sci(x):
        if x == 0:
            return '0'
        e = math.floor(math.log10(x))
        return r'\ensuremath{%s\times 10^{%d}}' % (f'{x / 10 ** e:.0f}', e)

    # ---- the direction fix, the second checkpoint and integrated gradients
    # Every tau and top-path number here uses the definitions of the main
    # table (analyze.order_tau, order_top_gap), so they can be read side by side.
    from pathfaith.analyze import order_tau, order_top_gap, kendall_tau

    def finite(x):
        return x == x

    def taus(rows):
        out = {}
        for r in rows:
            t = order_tau(r['true_drops'])
            if finite(t):
                out[(r['h'], r['r'], r['t'])] = t
        return out

    def emit_ci(name, triple, nd=3, as_pct=False):
        m, lo, hi = triple[:3]
        f = (lambda v: pct(v, nd)) if as_pct else (lambda v: fmt(v, nd))
        emit(name, f(m), lines)
        emit(name + 'CI', f'[{f(lo)}, {f(hi)}]', lines)

    dir_all = []
    for ds, pre in MACRO.items():
        lc = ds.lower()
        rel_path = os.path.join(args.results, f'paths_{lc}_seed0.jsonl')
        released = load(rel_path)[1] if os.path.exists(rel_path) else []
        # the benchmark with the direction-corrected explanation (Fx), and the
        # same on ULTRA's 3-graph checkpoint (Tg), with the released numbers'
        # definitions so the columns compare like with like
        for tag, fname in (('Fx', f'paths_{lc}_fixed_seed0.jsonl'),
                           ('Tg', f'paths_{lc}_3g_fixed_seed0.jsonl')):
            p = os.path.join(args.results, fname)
            if not os.path.exists(p):
                continue
            _, rows = load(p)
            if len(rows) < 10:
                continue
            rep = Summary(dataset=ds, rows=rows).report()
            emit(f'{pre}{tag}N', str(len(rows)), lines)
            for key in ('comp_frac_of_base', 'comp_random_frac_of_base', 'kendall_tau_grad_vs_drop',
                        'top1_is_best', 'top1_chance', 'bottleneck_frac',
                        'single_edge_recovers_frac'):
                emit_ci(macro_name(pre, tag, *[w.capitalize() for w in key.split('_')]), rep[key])
            # paired against the released explanation on the same queries
            if tag == 'Fx' and released:
                a, b = taus(released), taus(rows)
                keys = [k for k in b if k in a]
                if keys:
                    emit_ci(f'{pre}FxTauGain', boot([b[k] - a[k] for k in keys]))
                    emit_ci(f'{pre}FxPairedRel', boot([a[k] for k in keys]))
                    emit_ci(f'{pre}FxPairedFix', boot([b[k] for k in keys]))
                    emit(f'{pre}FxPairs', str(len(keys)), lines)
        b3 = os.path.join(args.results, f'baseline3g_{lc}_full.json')
        if os.path.exists(b3):
            b = json.load(open(b3))
            emit(f'{pre}TgMrr', fmt(b['mrr']), lines)
            emit(f'{pre}TgHitsOne', fmt(b['hits@1']), lines)
            emit(f'{pre}TgHitsTen', fmt(b['hits@10']), lines)
            emit(f'{pre}TgBaseN', f"{b['n_triples']:,}".replace(',', '{,}'), lines)

        # the message-direction check (pathfaith.direction_check)
        p = os.path.join(args.results, f'direction_{lc}.jsonl')
        if os.path.exists(p):
            _, rows = load(p)
            if rows:
                dir_all += rows
                emit(f'{pre}DirN', str(len(rows)), lines)
                emit(f'{pre}DirGapMax', fmt(max(r['gap_released'] for r in rows), 1), lines)

        # integrated gradients against the corrected gradient, same candidates
        p = os.path.join(args.results, f'ig_{lc}_seed0.jsonl')
        if os.path.exists(p):
            _, rows = load(p)
            rows = [r for r in rows if len(r['true_drops']) >= 2]
            if rows:
                tg = [order_tau(r['true_drops']) for r in rows]
                ti = [order_tau(r['true_drops'], r['path_ig']) for r in rows]
                ok = [i for i in range(len(rows)) if finite(tg[i]) and finite(ti[i])]
                emit(f'{pre}IgN', str(len(ok)), lines)
                emit_ci(f'{pre}IgGradTau', boot([tg[i] for i in ok]))
                emit_ci(f'{pre}IgTau', boot([ti[i] for i in ok]))
                emit_ci(f'{pre}IgTauGain', boot([ti[i] - tg[i] for i in ok]))
                emit_ci(f'{pre}IgGradTopGap', boot([order_top_gap(r['true_drops']) for r in rows]))
                emit_ci(f'{pre}IgTopGap', boot([order_top_gap(r['true_drops'], r['path_ig'])
                                               for r in rows]))
                gaps = np.array([r['completeness_gap'] for r in rows])
                tot = np.array([abs(r['base_prob'] - r['p_empty']) for r in rows])
                emit(f'{pre}IgCompGap', fmt(float(np.median(gaps)), 3), lines)
                emit(f'{pre}IgCompTotal', fmt(float(np.median(tot)), 3), lines)
                emit(f'{pre}IgCompGapRel', pct(float(np.median(gaps / np.maximum(tot, 1e-12))), 0), lines)
                # the same integral with the released code path's gradient
                q = os.path.join(args.results, f'ig_{lc}_released_seed0.jsonl')
                if os.path.exists(q):
                    rr = {(d['h'], d['r'], d['t']): d for d in load(q)[1]}
                    pair = [(rr[(r['h'], r['r'], r['t'])], r) for r in rows
                            if (r['h'], r['r'], r['t']) in rr]
                    if pair:
                        relg = lambda d: d['completeness_gap'] / max(abs(d['base_prob'] - d['p_empty']), 1e-12)
                        emit(f'{pre}IgRelGapN', str(len(pair)), lines)
                        emit(f'{pre}IgRelGapReleased', pct(float(np.median([relg(a) for a, _ in pair])), 0), lines)
                        emit(f'{pre}IgRelGapCorrected', pct(float(np.median([relg(b) for _, b in pair])), 0), lines)
                # channel level, on the channels the neuromodulation run dosed
                # (explained and gradient-ranked), with the definitions of the
                # neuromodulation summary: per query, then averaged
                q = os.path.join(args.results, f'neuromod_{lc}_seed0.jsonl')
                if os.path.exists(q):
                    nmr = {(d['h'], d['r'], d['t']): d for d in rows_of(q)[1]}
                    cg, ci_, sg, si = [], [], [], []
                    for r in rows:
                        d = nmr.get((r['h'], r['r'], r['t']))
                        if not d or d['base_prob'] <= 0:
                            continue
                        dosed = [c for c in d['channels'] if c['role'] in ('explained', 'gradient')]
                        eff = [(d['base_prob'] - c['doses']['0.0'][0]) / d['base_prob'] for c in dosed]
                        if len(dosed) >= 3:
                            a = kendall_tau([c['grad'] for c in dosed], eff)
                            b = kendall_tau([r['channel_ig'][c['c']] for c in dosed], eff)
                            if finite(a) and finite(b):
                                cg.append(a); ci_.append(b)
                        m = [(c, e) for c, e in zip(dosed, eff) if abs(e) >= 0.05]
                        if m:
                            sg.append(float(np.mean([np.sign(c['grad']) == np.sign(e) for c, e in m])))
                            si.append(float(np.mean([np.sign(r['channel_ig'][c['c']]) == np.sign(e)
                                                     for c, e in m])))
                    if cg:
                        emit_ci(f'{pre}IgChanGradTau', boot(cg))
                        emit_ci(f'{pre}IgChanTau', boot(ci_))
                    if sg:
                        emit_ci(f'{pre}IgChanGradSign', boot(sg), 1, True)
                        emit_ci(f'{pre}IgChanSign', boot(si), 1, True)
                        emit(f'{pre}IgChanN', str(len(sg)), lines)

    if dir_all:
        fd = np.array([r['fd'] for r in dir_all])
        fw = np.array([r['fd_wide'] for r in dir_all])
        dr = np.array([r['dir_released'] for r in dir_all])
        dc = np.array([r['dir_corrected'] for r in dir_all])
        emit('allDirN', str(len(dir_all)), lines)
        emit('allDirGapMin', fmt(min(r['gap_released'] for r in dir_all), 1), lines)
        emit('allDirGapMax', fmt(max(r['gap_released'] for r in dir_all), 1), lines)
        emit('allDirGapCorrected', sci(max(r['gap_corrected'] for r in dir_all)), lines)
        emit('allDirErrCorrected', pct(float(np.median(np.abs(dc - fd) / np.abs(fd))), 1), lines)
        emit('allDirErrReleased', pct(float(np.median(np.abs(dr - fd) / np.abs(fd))), 0), lines)
        emit('allDirErrCorrectedWide', pct(float(np.median(np.abs(dc - fw) / np.abs(fw))), 1), lines)
        emit('allDirErrReleasedWide', pct(float(np.median(np.abs(dr - fw) / np.abs(fw))), 0), lines)
        emit('allDirWithinTenCorrected', str(int((np.abs(dc - fd) / np.abs(fd) < 0.1).sum())), lines)
        emit('allDirWithinTenReleased', str(int((np.abs(dr - fd) / np.abs(fd) < 0.1).sum())), lines)
        emit('allDirSignReleased', str(int((np.sign(dr) != np.sign(fd)).sum())), lines)
        emit('allDirSignCorrected', str(int((np.sign(dc) != np.sign(fd)).sum())), lines)
        # one channel per query, the explained channel where the two gradients
        # disagree most; each gradient's sign against the measured slope of
        # the gain curve at 1, a central difference over gains 0.9 and 1.1
        ch = [r['channel'] for r in dir_all if 'channel' in r]
        slope = []
        for c in ch:
            g = [round(x, 2) for x in c['gains']]
            slope.append((c['p'][g.index(1.1)] - c['p'][g.index(0.9)]) / 0.2)
        emit('allDirChanN', str(len(ch)), lines)
        emit('allDirChanWrong', str(sum(c['grad_released'] * c['grad_corrected'] < 0 for c in ch)), lines)
        emit('allDirChanSlopeWrongReleased',
             str(sum(np.sign(c['grad_released']) != np.sign(s_) for c, s_ in zip(ch, slope))), lines)
        emit('allDirChanSlopeWrongCorrected',
             str(sum(np.sign(c['grad_corrected']) != np.sign(s_) for c, s_ in zip(ch, slope))), lines)

    if len(nm_gaps) == len(MACRO):
        emit('allNmCheckGap', sci(max(nm_gaps)), lines)
        emit('allNmQueries', f'{nm_total:,}'.replace(',', '{,}'), lines)

    # totals across every graph, for the benchmark-design slide
    tq = td = 0
    for ds in MACRO:
        pth = os.path.join(args.results, f'paths_{ds.lower()}_seed0.jsonl')
        if os.path.exists(pth):
            _, rws = load(pth)
            tq += len(rws)
            td += sum(len(r['true_drops']) for r in rws)
    emit('allQueries', f'{tq:,}'.replace(',', '{,}'), lines)
    emit('allDeletions', f'{td:,}'.replace(',', '{,}'), lines)

    # ranges across the four graphs, so a sentence like "between X and Y on
    # every graph" is computed rather than read off the table by eye; left
    # undefined, and so stubbed as ??, until all four graphs have data
    def val(name):
        for l in lines:
            m = re.match(r'\\newcommand\{\\' + name + r'\}\{(.+)\}$', l)
            if m:
                return float(m.group(1).replace(r'\ensuremath{-}', '-'))
        return None
    for key in ('CompFracOfBase', 'CompRandomFracOfBase', 'KendallTauGradVsDrop',
                'NmBest', 'NmRandom', 'NmHalfDose', 'NmJointHalf',
                'NmSignAgree', 'NmJoint', 'NmContent', 'NmSwitch', 'NmInvertedU', 'NmTau'):
        vals = [val(MACRO[ds] + key) for ds in MACRO]
        if all(v is not None for v in vals):
            emit(f'all{key}Min', fmt(min(vals), 3), lines)
            emit(f'all{key}Max', fmt(max(vals), 3), lines)

    # Any macro the manuscript references but the data does not yet define is
    # stubbed as ?? rather than left undefined, so a missing experiment shows
    # up as a visible gap in the PDF instead of a failed build.
    defined = {m.group(1) for l in lines
               for m in [re.match(r'\\newcommand\{\\([A-Za-z]+)\}', l)] if m}
    tex = os.path.join(os.path.dirname(args.out) or '.', 'main.tex')
    if os.path.exists(tex):
        used = set()
        for src in [tex] + [os.path.join(os.path.dirname(args.out) or '.', '..', d, f)
                            for d, f in (('presentation', 'talk.tex'), ('video', 'slides.tex'))]:
            if os.path.exists(src):
                used |= set(re.findall(r'\\((?:wn|fb|cx|nl|all)[A-Z][A-Za-z]*)', open(src).read()))
        for name in sorted(used - defined):
            lines.append(f'\\providecommand{{\\{name}}}{{\\textbf{{??}}}}')

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {args.out} with {len(lines) - 1} macros')


if __name__ == '__main__':
    main()
